# ==================== 查询与解读 ====================

def lookup(gua_name: str) -> Optional[Dict]:
    """按卦名查询卦辞数据"""
    return GUA64_DATA.get(gua_name)


def lookup_by_gua(up: str, down: str) -> Optional[Dict]:
    """按上下卦查询"""
    info = GUA64.get((up, down))
    if info:
        return GUA64_DATA.get(info['name'])
    return None


def interpret_for_question(gua_name: str, question: str) -> str:
    """结合所问之事给出义理解读"""
    data = lookup(gua_name)
    if not data:
        return f'未找到「{gua_name}」的卦辞数据。'

    out = []
    out.append(f"【{gua_name}】卦序{data['序']}  {data['上卦']}{data['下卦']}")
    out.append(f"卦辞：{data['卦辞']}")
    out.append(f"象曰：{data['象']}")
    out.append("")
    out.append(f"【卦义】{data['义理']}")
    if question:
        out.append("")
        out.append(f"【所问】{question}")
        out.append(f"引用卦辞：{data['卦辞']}")
        out.append(f"义理启发：{data['义理'].split('。')[0]}。结合所问，宜参考此理行事。")
    return "\n".join(out)


# ==================== 主函数 ====================

def main():
    def error_response(code, details):
        return {"success": False,
                "error": {"code": code,
                          "details": details if isinstance(details, list) else [details]}}

    if len(sys.argv) > 1 and sys.argv[1] in ('--help', '-h'):
        print("周易义理推演工具 v1.0（《周易》卦辞·彖传·象传）")
        print("用法:")
        print("  python yijing.py <卦名> [问题]")
        print("  python yijing.py list          # 列出全部64卦卦名")
        print("示例:")
        print("  python yijing.py 水雷屯 近期发展")
        print("  python yijing.py 风山渐 事业发展")
        print("  python yijing.py list")
        sys.exit(0)

    if len(sys.argv) < 2:
        print(json.dumps(error_response("MISSING_ARGUMENTS",
                                        "用法: python yijing.py <卦名> [问题]"),
                         ensure_ascii=False, indent=2))
        sys.exit(1)

    if sys.argv[1] == 'list':
        for i, (name, data) in enumerate(sorted(GUA64_DATA.items(), key=lambda x: x[1]['序']), 1):
            print(f"  {data['序']:2d}. {name:<12s} {data['上卦']}{data['下卦']}  "
                  f"{data['卦辞'][:20]}")
        print(f"\n共 {len(GUA64_DATA)} 卦")
        sys.exit(0)

    gua_name = sys.argv[1]
    question = ' '.join(sys.argv[2:]) if len(sys.argv) > 2 else None

    data = lookup(gua_name)
    if not data:
        print(json.dumps(error_response("GUA_NOT_FOUND",
                                        f"未找到卦名「{gua_name}」，请检查卦名是否为标准六十四卦名"),
                         ensure_ascii=False, indent=2))
        sys.exit(2)

    print(interpret_for_question(gua_name, question))

    result = {
        'name': gua_name,
        'order': data['序'],
        'gua_xiang': data['卦象'],
        'gua_ci': data['卦辞'],
        'tuan': data['彖'],
        'xiang': data['象'],
        'yi_li': data['义理'],
        'question': question,
    }
    print("\n\n[JSON_OUTPUT]")
    print(json.dumps({"success": True, "data": result}, ensure_ascii=False, indent=2))


if __name__ == '__main__':
    main()
